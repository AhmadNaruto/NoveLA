#include "lexbor/encoding/encoding.h"
#include "lexbor/encoding/multi.h"


int
main(void)
{
    FILE *fc;
    size_t i, size;
    unsigned lead, trail;
    lxb_codepoint_t cp;
    const char *filepath = "./shift_jis_map_decode.txt";

    fc = fopen(filepath, "w");
    if (fc == NULL) {
        printf("Failed to open file: %s\n", filepath);
        return EXIT_FAILURE;
    }

    fprintf(fc, "#\n"
            "# Copyright (C) 2019-2026 Alexander Borisov\n"
            "#\n"
            "# Author: Alexander Borisov <borisov@lexbor.com>\n"
            "#\n\n"
            "#\n"
            "# This file generated by the program\n"
            "# \"utils/lexbor/encoding/shift_jis_map_decode.c\"\n"
            "# All valid byte sequences, including duplicates and Private Use Area.\n"
            "#\n\n");

    size = sizeof(lxb_encoding_multi_jis0208_map) / sizeof(lxb_codepoint_t);

    for (i = 0; i < size; i++) {
        if (i >= 8836 && i <= 10715) {
            cp = 0xE000 + i - 8836;
        }
        else {
            cp = lxb_encoding_multi_jis0208_map[i];
            if (cp == LXB_ENCODING_ERROR_CODEPOINT) {
                continue;
            }
        }

        lead = i / 188;
        trail = i % 188;

        fprintf(fc, "\\x%02X\\x%02X 0x%04X\n",
                lead + ((lead < 0x1F) ? 0x81 : 0xC1),
                trail + ((trail < 0x3F) ? 0x40 : 0x41), (unsigned) cp);
    }

    for (cp = 0xFF61; cp <= 0xFF9F; cp++) {
        fprintf(fc, "\\x%02X 0x%04X\n", (unsigned) (cp - 0xFF61 + 0xA1),
                (unsigned) cp);
    }

    for (cp = 0x00; cp <= 0x80; cp++) {
        fprintf(fc, "\\x%02X 0x%04X\n", (unsigned) cp, (unsigned) cp);
    }

    fprintf(fc, "\n# END\n");

    return (fclose(fc) == 0) ? EXIT_SUCCESS : EXIT_FAILURE;
}
